const TRANSLATIONS: Record<Locale, TranslationDict> = {
  en,
  'pt-BR': ptBR,
  es,
  fr,
  de,
};

const GROUP_KEY_MAP: Record<FoodGroup, { name: TranslationKey; desc: TranslationKey }> = {
  'Water & Hydration': { name: 'groupWater', desc: 'groupDescWater' },
  'Grains & Starches': { name: 'groupGrains', desc: 'groupDescGrains' },
  'Proteins & Legumes': { name: 'groupProteins', desc: 'groupDescProteins' },
  'Fruits & Vegetables': { name: 'groupProduce', desc: 'groupDescProduce' },
  'Dairy & Alternatives': { name: 'groupDairy', desc: 'groupDescDairy' },
  'Fats, Oils & Condiments': { name: 'groupFats', desc: 'groupDescFats' },
  'Ready-to-Eat Meals': { name: 'groupMeals', desc: 'groupDescMeals' },
};

const STORAGE_KEY = 'stockkeep-locale';

function detectInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
  if (saved && saved in TRANSLATIONS) return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('pt')) return 'pt-BR';
  if (nav.startsWith('es')) return 'es';
  if (nav.startsWith('fr')) return 'fr';
  if (nav.startsWith('de')) return 'de';
  return 'en';
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  tGroup: (group: FoodGroup) => string;
  tGroupDesc: (group: FoodGroup) => string;
  tCadence: (freq: DigestFrequency) => string;
  formatNumber: (n: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  function setLocale(next: Locale) {
    setLocaleState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }

  function t(key: TranslationKey, vars?: Record<string, string | number>): string {
    const template = TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key];
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, k) =>
      vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
    );
  }

  function tGroup(group: FoodGroup): string {
    return t(GROUP_KEY_MAP[group].name);
  }

  function tGroupDesc(group: FoodGroup): string {
    return t(GROUP_KEY_MAP[group].desc);
  }

  function tCadence(freq: DigestFrequency): string {
    if (freq === 'immediate') return t('cadenceImmediate');
    if (freq === 'weekly') return t('cadenceWeekly');
    return t('cadenceDaily');
  }

  function formatNumber(n: number): string {
    return n.toLocaleString(locale);
  }

  return (
    <I18nContext.Provider
      value={{ locale, setLocale, t, tGroup, tGroupDesc, tCadence, formatNumber }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return ctx;
}
